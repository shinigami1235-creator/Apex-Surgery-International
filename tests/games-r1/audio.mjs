// Music and sound-effect toggles: off by default, remembered, files load and decode, track follows the game.
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
process.env.PLAYWRIGHT_BROWSERS_PATH = process.env.PLAYWRIGHT_BROWSERS_PATH || '/opt/pw-browsers';
const { chromium } = require('/home/claude/.npm-global/lib/node_modules/playwright');
const BASE = process.env.BASE || 'http://127.0.0.1:8765';
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage();
const errors = [], audio = [];
page.on('pageerror', e => errors.push(String(e)));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('response', r => { if (r.url().includes('/games/audio/')) audio.push(`${r.status()} ${r.url().split('/').pop()}`); });
const ok = (c, m) => console.log(`${c ? 'PASS' : 'FAIL'} ${m}`);
await page.goto(`${BASE}/lab/games.html?lang=en`, { waitUntil: 'networkidle' });
await page.evaluate(() => { Object.keys(localStorage).filter(k => k.startsWith('apxg.')).forEach(k => localStorage.removeItem(k)); });
await page.reload({ waitUntil: 'networkidle' });
ok(await page.getAttribute('.g-head [data-act=music]', 'aria-pressed') === 'false', 'music off by default');
ok(await page.getAttribute('.g-head [data-act=sfx]', 'aria-pressed') === 'false', 'sound effects off by default');
ok(audio.length === 0, 'no audio fetched while both are off');
await page.click('.g-head [data-act=music]');
await page.click('.g-head [data-act=sfx]');
await page.waitForTimeout(2500);
ok(await page.evaluate(() => localStorage.getItem('apxg.music')) === 'true', 'music choice stored');
ok(audio.some(a => a.startsWith('200 music-hub.mp3')), 'hub theme loaded: ' + audio.filter(a => a.includes('music')).join(', '));
ok(audio.filter(a => a.includes('sfx-')).length >= 10, 'effects loaded: ' + audio.filter(a => a.includes('sfx-')).length);
await page.reload({ waitUntil: 'networkidle' });
ok(await page.getAttribute('.g-head [data-act=music]', 'aria-pressed') === 'true', 'music choice remembered after reload');
await page.click('[data-game=memorymatch] [data-act=open]');
await page.click('[data-act=practice]');
await page.waitForTimeout(3500);
ok(audio.some(a => a.startsWith('200 music-memorymatch.mp3')), 'game track loaded on start');
const st = await page.evaluate(async () => {
  const r = await fetch('/assets/features/games/audio/music-steady.mp3'); const ab = await r.arrayBuffer();
  const ctx = new OfflineAudioContext(2, 48000, 48000); const b = await ctx.decodeAudioData(ab); return { dur: b.duration, sr: b.sampleRate };
});
ok(st.dur > 31.9, `steady loop decodes: ${st.dur.toFixed(2)} s (cycle 30 s plus margins)`);
await page.click('.g-hud [data-act=music]');
ok(await page.evaluate(() => localStorage.getItem('apxg.music')) === 'false', 'music switched off from the play bar');
ok(errors.length === 0, 'no page errors ' + errors.join(' | '));
await browser.close();
