import json, sys
m = {}
for line in open('/usr/share/zoneinfo/zone.tab'):
    if line.startswith('#') or not line.strip(): continue
    cc, _, tz = line.split('\t')[:3]
    m[tz.strip()] = cc
# links: aliases point at a zone that has a country
for line in open('/usr/share/zoneinfo/tzdata.zi'):
    p = line.split()
    if len(p) == 3 and p[0] == 'L' and p[1] in m and p[2] not in m:
        m[p[2]] = m[p[1]]
# group by prefix to keep it small: {"Asia":{"Bangkok":"TH",...}}
g = {}
for tz, cc in sorted(m.items()):
    if '/' in tz:
        a, b = tz.split('/', 1); g.setdefault(a, {})[b] = cc
    else:
        g.setdefault('', {})[tz] = cc
out = sys.argv[1]
open(out, 'w').write('/* Time zone to country, from the IANA zone.tab and its links (tzdata 2026). Used on the design preview,\n   which has no server to say where the visitor is. Generated by build/pricing_tz.py. */\nexport default ' + json.dumps(g, separators=(',', ':')) + ';\n')
print(len(m), 'zones')
